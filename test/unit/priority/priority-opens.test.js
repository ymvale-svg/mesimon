'use strict';
/**
 * סקירה לילית 15.11: המילה "פריוריטי" / "דרישת רכש" בתוך בקשה אחרת פתחה את פריוריטי:
 *   • "שלח מייל ל… שנקבעה פגישה בעניין הערבויות בפריוריטי" — נפתח תפריט פריוריטי, והמייל לא נוסח.
 *   • "תגיד לי מה הדרישות רכש הפתוחות בפרויקט…" / "תראה לי את דרישת רכש …" — נפתחה דרישה חדשה.
 * עכשיו: בקשה אחרת (מייל, משימה, תזכורת) או שאלה — לא פותחת קליטה / דרישה. "פריוריטי", "דרישת רכש",
 * "קבלת סחורה", הכפתורים וקובץ בלי טקסט — כמו קודם.
 */
const test = require('node:test');
const assert = require('node:assert/strict');
require('../../helpers/db').boot();
const GR = require('../../../server/priority/goods-receipt');
const PD = require('../../../server/priority/purchase-demand');

test('בקשה אחרת או שאלה שמזכירה את פריוריטי — לא פותחת', () => {
  for (const t of ['שלח מייל להורית שנקבעה פגישה ביום שלישי בעניין הערבויות בפריוריטי',
    'תכתוב לדני שהדרישה בפריוריטי אושרה', 'תפתח לי משימה לבדוק את ההרשאות בפריוריטי', 'מה קורה עם פריוריטי?',
    'תזכיר לי מחר לעשות קבלת סחורה'])
    assert.equal(GR.opens(t, null), false, t);
  for (const t of ['תגיד לי מה הדרישות רכש הפתוחות בפרויקט אלעד סנטר', 'תראה לי את דרישת רכש PR26000004',
    'כמה דרישות רכש פתוחות?', 'שלח מייל לשזר על דרישת הרכש'])
    assert.equal(PD.opens(t), false, t);
});

test('פתיחה רגילה — כמו קודם', () => {
  for (const t of ['פריוריטי', '🗂 פריוריטי', 'קבלת סחורה', '📦 קבלת סחורה', 'אני רוצה לעשות קבלת סחורה', 'קבלת סחורה לאלעד'])
    assert.equal(GR.opens(t, null), true, t);
  assert.equal(GR.opens('', { path: 'x.jpg' }), true, 'קובץ בלי טקסט');
  for (const t of ['דרישת רכש', '🛒 דרישת רכש', 'תפתח דרישת רכש לאלעד', 'דרישת רכש: 5 שקי מלט'])
    assert.equal(PD.opens(t), true, t);
});

// סקירה לילית 23.11: "נסח לי את המייל ⏎ … אנחנו עושים 'קבלת סחורה' …" — נפתחה קבלת סחורה במקום ניסוח המייל.
// "נסח" (בלי ת') לא היה ברשימת הבקשות האחרות.
test('בקשת ניסוח שמצטטת "קבלת סחורה" — לא פותחת', () => {
  for (const t of ["נסח לי את המייל\nשלום, כרגע אנחנו עושים 'קבלת סחורה' לחשבונות מים וחשמל ומעבירים להנהלת חשבונות",
    'נסחי מייל לספק על קבלת סחורה שלא הגיעה', 'ענה לו שקבלת הסחורה נעשתה', 'ענה לה בבקשה על קבלת הסחורה', 'כתבי לשקמה שקבלת סחורה בוצעה'])
    assert.equal(GR.opens(t, null), false, t);
  assert.equal(PD.opens('נסח מייל לרכש על דרישת רכש שתקועה'), false);
});
