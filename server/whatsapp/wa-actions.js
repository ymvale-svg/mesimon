/*
 * 📖 "תן לי את כל התכונות שלך" (‎featuresText‎ ב-‎wa-bot.js‎) נבנה מהקטלוג הזה — לא הודעה קבועה (הוחלט 10.11.26, ישראל:
 * "שהאופציות יתעדכנו בהתאם להתפתחות של הבוט"). לכל פעולה: ‎section‎ (הפרק) ו-‎feature‎ (שורה לעובד, קצרה);
 * ‎control‎ — שורות ל"יותר מדי? אתה בשליטה"; ‎requires‎ — פעולה שבלעדיה השורה לא מוצגת. פעולה חדשה בלי ‎feature‎ — נכנסת לבד, מהתווית והדוגמה הראשונה,
 * בפרק "עוד". פעולה כבויה או לא מורשית לכותב — לא מוצגת.
 */
const SECTIONS = [
  ['today', '☀️ *היום שלך*'], ['mail', '📧 *מיילים — רק מה שחשוב*'], ['meetings', '📅 *פגישות*'],
  ['docs', '✍️ *מסמכים ופניות*'], ['ask', '✨ *שאלות ובעיות*'], ['priority', '🗂 *פריוריטי*'],
  ['tasks', '📝 *משימות ותזכורות*'], ['other', '➕ *עוד*']
];

const AUDIENCES = ['all', 'managers'];

/** הקטלוג עם מה שנשמר במסך הניהול */
function list() {
  const saved = D.getSetting('wa_actions', {}) ?? {};
  return ACTIONS.map((a) => {
    const s = saved[a.key] ?? {};
    return {
      ...a,
      enabled: typeof s.enabled === 'boolean' ? s.enabled : a.enabled,
      audience: AUDIENCES.includes(s.audience) ? s.audience : 'all',
      examples: Array.isArray(s.examples) ? s.examples : a.examples,
      defaultExamples: a.examples
    };
  });
}

const byKey = (key) => list().find((a) => a.key === key) ?? null;

/** מנהל = מי שאינו עובד מן השורה. הנהלה ומנהלי מחלקות */
const isManager = (actor) => actor?.type === 'user' && actor.role !== 'employee';

/*
 * 🧪 פיילוט (הוחלט 09.11.26): היכולות החדשות מסבב Instinct — רק למנהלי המערכת, עד שפותחים אותן לכולם
 * ("פתח את היכולות החדשות לכולם" בבוט, או ההגדרה ‎bot_pilot‎). כך הבדיקה בבוט האמיתי לא מגיעה לעובדים.
 */
const PILOT_KEYS = new Set(['reminders', 'sent_followup', 'day_digest', 'briefing', 'translate', 'meeting_followup', 'meeting_audio', 'mail_deadline', 'goods_offer', 'notices', 'rfq', 'form_fill', 'meet_coord']);
const PILOT_ROLES = ['superadmin', 'admin'];
const inPilot = (actor) => actor?.type === 'user' && PILOT_ROLES.includes(actor.role);

function allowed(actor, key) {
  const a = byKey(key);
  if (PILOT_KEYS.has(key) && D.getSetting('bot_pilot', false) && !inPilot(actor)) return false;
  return Boolean(a?.enabled && (a.audience === 'all' || isManager(actor)));
}

const forActor = (actor) => list().filter((a) => a.channel === 'private' && allowed(actor, a.key));

function save(input) {
  const saved = {};
  for (const a of ACTIONS) {
    const x = (Array.isArray(input) ? input : []).find((i) => i?.key === a.key);
    if (!x) continue;
    saved[a.key] = {
      enabled: Boolean(x.enabled),
      audience: AUDIENCES.includes(x.audience) ? x.audience : 'all',
      examples: (Array.isArray(x.examples) ? x.examples : []).map((e) => String(e).trim().slice(0, 200)).filter(Boolean).slice(0, 6)
    };
  }
  D.setSetting('wa_actions', saved);
}

module.exports = {
  PILOT_KEYS, SECTIONS, inPilot, list, byKey, allowed, forActor, save, isManager };
