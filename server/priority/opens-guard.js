'use strict';
/**
 * 🚦 מתי מילה של פריוריטי ("פריוריטי", "קבלת סחורה", "דרישת רכש") לא פותחת את פריוריטי (סקירה לילית 15.11.26).
 *
 * המילה מופיעה גם בתוך בקשה אחרת — "שלח מייל ל… בעניין הערבויות בפריוריטי", "תפתח לי משימה לבדוק את פריוריטי" —
 * ובשאלה על מה שכבר יש — "מה הדרישות רכש הפתוחות?", "תראה לי את דרישת רכש …". אלה הולכות לבוט הרגיל
 * (מייל, משימה, שאלה), ולא פותחות קליטה או דרישה חדשה.
 */
// בקשה אחרת: מייל, הודעה, ניסוח ("נסח לי את המייל …", 23.11.26), משימה, תזכורת, פגישה
const OTHER = /^\P{L}*ש?(?:שלח|תשלח|תשלחי|שלחי|תכתוב|תכתבי|כתוב|תנסח|תנסחי|נסח|נסחי|כתבי|תענה|תעני|ענה|תעביר|תעבירי|העבר|תזכיר|תזכירי|תקבע|תקבעי|קבע|מייל|משימה|(?:תפתח|תפתחי|פתח|תעשה|תעשי|תיצור|צור)\s+(?:לי\s+)?משימה)(?:\s|$)/u;
// שאלה על מה שכבר יש
const QUESTION = /^\P{L}*(?:מה|מהן|מהם|איזה|איזו|אילו|כמה|מי|איפה|מתי|למה|האם|תגיד|תגידי|תראה|תראי|הראה|תבדוק|תבדקי|בדוק|סטטוס)(?:\s|$)/u;

/** ‎true‎ — ההודעה היא בקשה אחרת או שאלה, גם אם היא מזכירה את פריוריטי */
function notOpening(text) {
  const t = String(text ?? '').trim();
  return OTHER.test(t) || QUESTION.test(t) || /\?\s*$/.test(t);
}

module.exports = { notOpening };
